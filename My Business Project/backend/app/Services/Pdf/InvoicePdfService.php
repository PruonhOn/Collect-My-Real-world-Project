<?php

namespace App\Services\Pdf;

use App\Models\BusinessInvoice;
use App\Services\Features\FeatureGate;
use Mpdf\Mpdf;

class InvoicePdfService
{
    public function __construct(protected FeatureGate $gate) {}

    public function render(BusinessInvoice $invoice): string
    {
        $business = $invoice->business;
        $branded = $invoice->is_branded && $this->gate->allows($business, 'branded_invoices');
        $appName = config('app.name', 'My Business');

        $html = $this->html($invoice, $business, $branded, $appName);

        $mpdf = new Mpdf([
            'mode' => 'utf-8',
            'format' => 'A4',
            'default_font' => 'dejavusans',
        ]);
        $mpdf->WriteHTML($html);

        return $mpdf->Output('', 'S');
    }

    protected function html(BusinessInvoice $invoice, $business, bool $branded, string $appName): string
    {
        $currency = $invoice->currency;
        $rows = '';

        foreach ((array) $invoice->line_items as $line) {
            $rows .= '<tr>
                <td>'.e($line['description']).'</td>
                <td class="right">'.(int) $line['quantity'].'</td>
                <td class="right">'.number_format((int) $line['unit_amount'] / 100, 2).' '.$currency.'</td>
                <td class="right">'.number_format((int) $line['amount'] / 100, 2).' '.$currency.'</td>
            </tr>';
        }

        $headerTitle = $branded ? $business->name : $appName;
        $footer = $branded
            ? ($business->address ?: '')
            : 'Generated by '.$appName;

        return <<<HTML
        <!DOCTYPE html>
        <html>
        <head>
        <meta charset="utf-8">
        <style>
            body { font-family: 'dejavusans', sans-serif; font-size: 12px; color: #111827; }
            h1 { font-size: 22px; margin: 0 0 4px 0; }
            .muted { color: #6b7280; }
            table { width: 100%; border-collapse: collapse; margin-top: 24px; }
            th, td { border-bottom: 1px solid #e5e7eb; padding: 8px 6px; }
            th { text-align: left; background: #f9fafb; }
            .right { text-align: right; }
            .totals { margin-top: 18px; width: 45%; float: right; }
            .totals td { border: none; padding: 4px 6px; }
            .brand { border-left: 4px solid #2563eb; padding-left: 12px; }
        </style>
        </head>
        <body>
            <div class="brand">
                <h1>{$headerTitle}</h1>
                <div class="muted">Invoice {$invoice->invoice_number}</div>
            </div>
            <p class="muted">Issue date: {$invoice->issue_date} &nbsp; | &nbsp; Due: {$invoice->due_date}</p>
            <table>
                <thead>
                    <tr><th>Description</th><th class="right">Qty</th><th class="right">Unit</th><th class="right">Amount</th></tr>
                </thead>
                <tbody>{$rows}</tbody>
            </table>
            <table class="totals">
                <tr><td>Subtotal</td><td class="right">{$currency} ".number_format($invoice->subtotal / 100, 2)."</td></tr>
                <tr><td>Discount</td><td class="right">{$currency} ".number_format($invoice->discount / 100, 2)."</td></tr>
                <tr><td>Tax</td><td class="right">{$currency} ".number_format($invoice->tax / 100, 2)."</td></tr>
                <tr><td><strong>Total</strong></td><td class="right"><strong>{$currency} ".number_format($invoice->total / 100, 2)."</strong></td></tr>
            </table>
            <p class="muted" style="margin-top:60px;">{$footer}</p>
        </body>
        </html>
        HTML;
    }
}
