export function getTranslation(locale, key) {
  const dict = translations[locale] || translations.km
  const resolve = (d) =>
    key
      .split('.')
      .reduce((obj, k) => (obj && k in obj ? obj[k] : undefined), d)
  return (
    resolve(dict) ||
    resolve(translations.en) ||
    resolve(translations.km) ||
    key
  )
}